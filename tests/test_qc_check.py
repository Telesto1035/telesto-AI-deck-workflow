def test_exit_codes(broken_dir, tmp_path, capsys):
    clean = FIXTURES / "Telesto_Standard_v2_P3-P5.pptx"
    assert qc_check.main([str(clean)]) == 0
    assert qc_check.main([str(broken_dir / "Telesto_Standard_v2_P3-P5.broken.pptx")]) == 1
    bad = tmp_path / "not_a_deck.pptx"
    bad.write_bytes(b"not a zip")
    assert qc_check.main([str(bad)]) == 2
    assert qc_check.main([str(tmp_path / "missing.pptx")]) == 2
    capsys.readouterr()


def test_json_output_schema(broken_dir, tmp_path, capsys):
    out = tmp_path / "findings.json"
    rc = qc_check.main([str(broken_dir / "Telesto_Package_Types.broken.pptx"), "--json", str(out)])
    capsys.readouterr()
    assert rc == 1
    payload = json.loads(out.read_text(encoding="utf-8"))
    assert payload["pass"] is False
    assert payload["counts"]["block"] > 0
    keys = {"id", "severity", "slide", "shape", "shape_id", "text", "detail", "fix", "auto_fixable"}
    for f in payload["findings"]:
        assert set(f) == keys, f
        assert f["severity"] in ("block", "warn", "info")
        assert f["fix"] in ("resize", "reword", "clear", "delete", "none")


def test_fix_safe_cli_writes_beside_input(broken_dir, capsys):
    src = broken_dir / "Telesto_Package_Types.broken.pptx"
    qc_check.main([str(src), "--fix-safe"])
    capsys.readouterr()
    fixed = src.with_name(src.stem + ".qc.pptx")
    assert fixed.exists()
    Presentation(str(fixed))


def test_runtime_under_five_seconds_on_38_slides(rules):
    src = FIXTURES / "telesto_v2_template.pptx"
    t0 = time.perf_counter()
    deck, _findings = qc_check.run_checks(src, rules)
    elapsed = time.perf_counter() - t0
    assert len(deck.slides) == 38
    assert elapsed < 5.0, elapsed


def test_profile_length_is_info_only(rules):
    src = FIXTURES / "Telesto_Standard_v2_P3-P5.pptx"
    _deck, findings = qc_check.run_checks(src, rules, profile="findings")
    dl = by_id(findings, "deck-length")
    assert dl and dl[0].severity == "info"
    _deck, findings = qc_check.run_checks(src, rules, profile="minipack")
    assert not by_id(findings, "deck-length")
