"""Tests for .claude/skills/deck-qc/scripts/qc_check.py against the bundled fixtures.

Fixtures come in pairs: the clean deck in tests/fixtures/ and a broken copy generated by
tests/make_broken.py with known faults. Every planted fault must be found and nothing else
may appear beyond what the clean deck already reports.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import pytest
from pptx import Presentation

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
SCRIPTS = REPO / ".claude" / "skills" / "deck-qc" / "scripts"
sys.path.insert(0, str(SCRIPTS))
sys.path.insert(0, str(HERE))

import qc_check  # noqa: E402
import make_broken  # noqa: E402

FIXTURES = HERE / "fixtures"
CLEAN = sorted(FIXTURES.glob("*.pptx"))
assert CLEAN, "no fixtures found in tests/fixtures"

# Blocking findings the clean fixtures carry as delivered. Only two of the four are clean under
# section 3 rules: the Deliverable Brief is a 9pt PptxGenJS one-pager with an italic caption and
# a populated author field; the template carries one italic quote on slide 24.
KNOWN_CLEAN_BLOCKS = {
    "Telesto_Standard_v2_P3-P5": set(),
    "Telesto_Package_Types": set(),
    "telesto_v2_template": set(),
    "Telesto_Deliverable_Brief_Example": {"author-empty", "metadata-scrub", "font-size-floor"},
}


@pytest.fixture(scope="session")
def rules() -> dict:
    return qc_check.load_rules(None)


@pytest.fixture(scope="session")
def name_rules(rules) -> dict:
    r = json.loads(json.dumps(rules))
    r["client_names"] = [make_broken.STAKEHOLDER]
    return r


@pytest.fixture(scope="session")
def broken_dir(tmp_path_factory) -> Path:
    out = tmp_path_factory.mktemp("broken")
    for src in CLEAN:
        make_broken.make_broken(src, out / (src.stem + ".broken.pptx"))
    return out


def ids(findings, severity=None):
    return {f.id for f in findings if severity is None or f.severity == severity}


def by_id(findings, fid):
    return [f for f in findings if f.id == fid]


# ---------------------------------------------------------------------------------------------
# clean fixtures
# ---------------------------------------------------------------------------------------------


@pytest.mark.parametrize("src", CLEAN, ids=[p.stem for p in CLEAN])
def test_clean_fixture_block_set_is_known(src, rules):
    _deck, findings = qc_check.run_checks(src, rules)
    assert ids(findings, "block") == KNOWN_CLEAN_BLOCKS[src.stem], [
        (f.id, f.slide, f.detail) for f in findings if f.severity == "block"
    ]


def test_fixtures_not_modified_in_place():
    for src in CLEAN:
        assert not (src.with_name(src.stem + ".qc.pptx")).exists(), "qc_check wrote beside a fixture"


