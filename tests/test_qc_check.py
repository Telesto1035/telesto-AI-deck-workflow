def test_fix_safe_clears_settled_faults_and_nothing_else(broken_dir, name_rules, tmp_path):
    broken = broken_dir / "Telesto_Standard_v2_P3-P5.broken.pptx"
    deck, findings = qc_check.run_checks(broken, name_rules)
    out = tmp_path / "fixed.qc.pptx"
    log = []
    qc_check.fix_safe(deck, findings, out, log.append)
    assert out.exists()
    Presentation(str(out))  # re-opens in python-pptx
    assert any("Build sequence" in line for line in log), "notes must be printed before they are stripped"

    _d2, after = qc_check.run_checks(out, name_rules)
    gone = {"speaker-notes", "semicolon-runs", "quote-marks"}
    assert not (gone & ids(after)), sorted(gone & ids(after))
    # Document properties survive: PowerPoint's Document Inspector owns that scrub, and nothing
    # in the chain rewrites a deck's properties behind the consultant.
    assert "author-empty" in ids(after), "fix_safe must not clear the author field"
    assert [f for f in by_id(after, "metadata-scrub") if "TotalTime" in f.detail], "TotalTime must survive"
    # never changes a number, a size or wording
    kept = {"font-size-floor", "totals-sum", "chart-cache-label", "placeholders", "footnote-sequence", "stakeholder-name"}
    assert kept <= ids(after), sorted(kept - ids(after))
    # the input is untouched
    _d3, again = qc_check.run_checks(broken, name_rules)
    assert ids(again, "block") == ids(findings, "block")


def test_fix_safe_in_place_keeps_the_deck(broken_dir, name_rules, tmp_path):
    """out_path may be the input deck itself; the rewrite must leave a valid PPTX behind."""
    deck_path = tmp_path / "in_place.pptx"
    deck_path.write_bytes((broken_dir / "Telesto_Standard_v2_P3-P5.broken.pptx").read_bytes())
    deck, findings = qc_check.run_checks(deck_path, name_rules)
    qc_check.fix_safe(deck, findings, deck_path, lambda s: None)
    Presentation(str(deck_path))
    _d2, after = qc_check.run_checks(deck_path, name_rules)
    assert "speaker-notes" not in ids(after)
    assert "author-empty" in ids(after), "document properties are a hand-back condition, not fix_safe's"
    # the temp file is moved over the deck, never left beside it
    assert sorted(p.name for p in tmp_path.iterdir()) == ["in_place.pptx"]


