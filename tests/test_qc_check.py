# broken fixtures: every planted fault found, nothing else
# ---------------------------------------------------------------------------------------------


@pytest.mark.parametrize("src", CLEAN, ids=[p.stem for p in CLEAN])
def test_broken_fixture_finds_every_planted_fault(src, broken_dir, rules, name_rules):
    broken = broken_dir / (src.stem + ".broken.pptx")
    _cd, clean_findings = qc_check.run_checks(src, rules)
    deck, findings = qc_check.run_checks(broken, name_rules)
    multi = len(deck.slides) > 1

    expected_blocks = KNOWN_CLEAN_BLOCKS[src.stem] | make_broken.PLANTED_BLOCK_IDS | make_broken.PLANTED_WITH_NAME_RULES
    assert ids(findings, "block") == expected_blocks, sorted(
        (f.id, f.slide, f.detail) for f in findings if f.severity == "block"
    )

    expected_warns = make_broken.PLANTED_WARN_IDS | (make_broken.PLANTED_MULTISLIDE_WARN_IDS if multi else set())
    new_warns = ids(findings, "warn") - ids(clean_findings, "warn")
    assert expected_warns <= ids(findings, "warn"), sorted(ids(findings, "warn"))
    assert new_warns <= expected_warns, "unplanted warn(s): %s" % sorted(new_warns - expected_warns)

    # each slide-level planted fault sits on slide 1, where make_broken put it
    for fid in ("font-size-floor", "italics", "placeholders", "totals-sum", "chart-cache-label",
                "footnote-sequence", "stakeholder-name", "label-in-bar", "semicolon-runs",
                "abbreviation-list", "empty-textbox", "off-canvas"):
        assert any(f.slide == 1 for f in by_id(findings, fid)), fid

    # font floor: the 9pt body run and the 7pt footnote list are both caught, by shape name
    floor = [f for f in by_id(findings, "font-size-floor") if f.slide == 1]
    assert len(floor) == 1, floor  # one finding per slide
    assert "QC body 9pt" in floor[0].detail and "QC footnotes" in floor[0].detail, floor[0].detail
    assert "outside a footnote home (smallest 9.0pt)" in floor[0].detail
    assert "footnote shape below 8pt (smallest 7.0pt)" in floor[0].detail

    # author and metadata
    assert {f.text for f in by_id(findings, "author-empty")} == {make_broken.AUTHOR}
    assert len(by_id(findings, "author-empty")) >= 2  # creator and lastModifiedBy
    meta = " | ".join(f.detail for f in by_id(findings, "metadata-scrub"))
    assert "TotalTime" in meta and "custom.xml" in meta
    tt = next(f for f in by_id(findings, "metadata-scrub") if "TotalTime" in f.detail)
    assert tt.text == make_broken.TOTAL_TIME
    custom = next(f for f in by_id(findings, "metadata-scrub") if "custom.xml" in f.detail)
    assert "ContentTypeId" in custom.text

    # speaker notes are reported in full
    notes = by_id(findings, "speaker-notes")
    assert notes and any(make_broken.NOTE_TEXT in f.text for f in notes)

    # placeholders
    assert any("[PLACEHOLDER: source needed]" in f.detail for f in by_id(findings, "placeholders"))

    # totals: 40 + 30 + 28 = 98 against 100
    tot = by_id(findings, "totals-sum")
    assert any("98" in f.detail and "100" in f.detail for f in tot), [f.detail for f in tot]

    # chart cache vs label
    ch = by_id(findings, "chart-cache-label")
    assert any(f.text == "36%" and "34" in f.detail for f in ch), [(f.text, f.detail) for f in ch]

    # footnote sequence: marker 4 orphaned, 3 skipped, footnote 3 never marked
    fs = " | ".join(f.detail for f in by_id(findings, "footnote-sequence"))
    assert "marker(s) 4 have no footnote" in fs
    assert "skips 3" in fs
    assert "footnote(s) 3 defined but never marked" in fs

    # abbreviation and stakeholder
    assert any("'State'" in f.detail for f in by_id(findings, "abbreviation-list"))
    assert any(make_broken.STAKEHOLDER in f.detail for f in by_id(findings, "stakeholder-name"))

    # hidden slide is the last one
    hidden = by_id(findings, "hidden-slides")
    assert [f.slide for f in hidden] == [len(deck.slides)]

    # off-canvas names the right edge
    assert any("right" in f.detail for f in by_id(findings, "off-canvas"))

    if multi:
        ds = by_id(findings, "draft-stamp")
        assert ds and ds[0].detail.startswith("DRAFT stamp on slides 1")


